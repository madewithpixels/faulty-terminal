import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url)));
const { version } = pkg;
const tag = `v${version}`;
const url = `https://cdn.jsdelivr.net/gh/madewithpixels/faulty-terminal@${tag}/dist/faulty-terminal.min.js`;
const js = readFileSync('dist/faulty-terminal.min.js');
const integrity = `sha384-${createHash('sha384').update(js).digest('base64')}`;

mkdirSync('webflow', { recursive: true });
writeFileSync('webflow/faulty-terminal-loader.html', `<!-- faulty-terminal ${version} — Site Settings > Custom Code > Footer.
     Generated by npm run build. Pinned with an SRI hash, so a tampered or
     truncated file is refused rather than executed. -->
<script
  defer
  src="${url}"
  integrity="${integrity}"
  crossorigin="anonymous"
  data-faulty-terminal-version="${version}"
  onerror="console.error('faulty-terminal ${version}: CDN script failed to load; .faulty-terminal elements will stay empty.');window.dispatchEvent(new CustomEvent('faulty-terminal:cdn-error',{detail:{version:'${version}'}}))"></script>
`);
console.log(`loader written for ${tag}\\n  ${integrity}`);
